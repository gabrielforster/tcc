#!/usr/bin/env bash
# Build the A0 poster: QR codes -> legibility check -> PDF -> PNG preview.
#
#   poster/export-pdf.sh            # writes poster/poster.pdf and poster/poster-preview.png
#   poster/export-pdf.sh out.pdf    # another PDF path (the preview lands next to it)
#
# Needs chromium (or google-chrome), qrencode and poppler's pdftoppm. Nothing is fetched:
# the page uses no web fonts and no CDN, so the build works offline.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
out="$(realpath -m "${1:-$here/poster.pdf}")"
preview="${out%.pdf}-preview.png"
[ "$out" = "$here/poster.pdf" ] && preview="$here/poster-preview.png"

browser="$(command -v chromium || command -v chromium-browser || command -v google-chrome-stable || true)"
[ -n "$browser" ] || { echo "needs chromium or google-chrome on PATH" >&2; exit 1; }
command -v qrencode >/dev/null || { echo "needs qrencode on PATH" >&2; exit 1; }

# shellcheck source=qr-targets.conf
. "$here/qr-targets.conf"

# --- 1. QR codes (vector SVG) and the captions the page reads ---------------------------
# Error correction Q (25%) so a scuffed or partly covered print still scans. Margin 0:
# the page draws the quiet zone itself, as white padding around each code.
mkdir -p "$here/qr"
qr() { # name url
  qrencode -t SVG -l Q -m 0 -s 1 -o "$here/qr/$1.svg" "$2"
}
qr prod "$PROD_URL"
qr repo "$REPO_URL"
qr docs "$DOCS_URL"
if [ -n "$VIDEO_URL" ]; then qr video "$VIDEO_URL"; else rm -f "$here/qr/video.svg"; fi

js_str() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }
cat > "$here/qr/targets.js" <<EOF
// Generated by export-pdf.sh from qr-targets.conf. Do not edit by hand.
window.POSTER_QR = {
  prod: "$(js_str "$PROD_URL")",
  repo: "$(js_str "$REPO_URL")",
  docs: "$(js_str "$DOCS_URL")",
  video: "$(js_str "$VIDEO_URL")"
};
EOF

# --- 2. Legibility check: no text under 20 pt -------------------------------------------
# poster.js measures every visible text node (SVG text included, scaled by its transform)
# and writes the smallest size into <html data-min-pt>. The build fails below 20.
url="file://$here/index.html"
dom="$("$browser" --headless=new --disable-gpu --no-sandbox --hide-scrollbars \
  --window-size=3179,4494 --virtual-time-budget=3000 --dump-dom "$url?check" 2>/dev/null)"
min_pt="$(printf '%s' "$dom" | grep -o 'data-min-pt="[^"]*"' | head -1 | cut -d'"' -f2)"
min_at="$(printf '%s' "$dom" | grep -o 'data-min-at="[^"]*"' | head -1 | cut -d'"' -f2)"
overflow="$(printf '%s' "$dom" | grep -o 'data-overflow="[^"]*"' | head -1 | cut -d'"' -f2)"
[ -n "$min_pt" ] || { echo "legibility check did not run (no data-min-pt)" >&2; exit 1; }
slack="$(printf '%s' "$dom" | grep -o 'data-slack-mm="[^"]*"' | head -1 | cut -d'"' -f2)"
echo "smallest text: ${min_pt} pt (${min_at}); free space above the footer: ${slack} mm"
awk -v m="$min_pt" 'BEGIN { exit !(m + 0 >= 20) }' || { echo "text below 20 pt" >&2; exit 1; }
if [ -n "$overflow" ]; then echo "content overflows its box: $overflow" >&2; exit 1; fi

# --- 3. PDF at A0 (the page sets @page 841mm x 1189mm) ----------------------------------
"$browser" --headless=new --disable-gpu --no-sandbox --hide-scrollbars \
  --virtual-time-budget=3000 --no-pdf-header-footer --print-to-pdf="$out" "$url" 2>/dev/null
pages="$(pdfinfo "$out" | awk '/^Pages:/ { print $2 }')"
size="$(pdfinfo "$out" | awk -F': *' '/^Page size:/ { print $2 }')"
[ "$pages" = 1 ] || { echo "expected 1 page, got $pages" >&2; exit 1; }
echo "$out: $pages page, $size, $(du -h "$out" | cut -f1)"

# --- 4. PNG preview (about 1/8 scale, for the README and quick review) ------------------
pdftoppm -png -r 40 -singlefile "$out" "${preview%.png}"
echo "$preview"
